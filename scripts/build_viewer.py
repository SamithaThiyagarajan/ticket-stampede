def utc_epoch(s, fmt):
    return datetime.datetime.strptime(s, fmt).replace(tzinfo=datetime.timezone.utc).timestamp()


def pct(xs, p):
    xs = sorted(xs)
    return xs[max(0, math.ceil(p * len(xs)) - 1)] if xs else None


def build(name, label, rid, caption):
    d = json.load(gzip.open(R / f"{name}.json.gz", "rt"))
    rate, recs = d["args"]["rate"], d["records"]
    t0 = d.get("start_at")
    env = (R / f"{name}.env").read_text()
    ip_name = dict(re.findall(r"(seller\d)=(\d+\.\d+\.\d+\.\d+)", env))
    seller_of = {f"{ip}:8000": s for s, ip in ip_name.items()}
    ans = lambda r: r["i"] / rate + r["latency_ms"] / 1000
    T = int(math.ceil(max(ans(r) for r in recs)))

    def cls(s):
        if s in (200, 409, 500, 502):
            return str(s)
        return "other" if isinstance(s, int) else ("never sent" if s in NEVER_SENT else "no answer")

    kinds = ["409", "200", "500", "502", "other", "no answer", "never sent"]
    per = [Counter() for _ in range(T + 1)]
    arrivals = [0] * (T + 1)
    lat = [[] for _ in range(T + 1)]
    sellers = {s: [Counter() for _ in range(T + 1)] for s in ("seller1", "seller2", "seller3")}
    nginx_own = [0] * (T + 1)                     # 502s generated by nginx itself (no live upstream)
    for r in recs:
        s = int(ans(r))
        per[s][cls(r["status"])] += 1
        arrivals[min(T, int(r["i"] / rate))] += 1
        if isinstance(r["status"], int):
            lat[s].append(r["latency_ms"])
        up = r.get("upstream")
        if up in seller_of and isinstance(r["status"], int):
            sellers[seller_of[up]][s][r["status"]] += 1
        elif up == "sellers":
            nginx_own[s] += 1
    first_ok = {}
    for r in sorted((r for r in recs if r["status"] == 200), key=ans):
        first_ok.setdefault(r["ticket_number"], ans(r))
    sold = [sum(1 for t in first_ok.values() if t < s + 1) for s in range(T + 1)]

    # Events (seconds relative to the buyer's t=0), from Docker's own event stream and the logs.
    events, pg_down, pg_ready = [], None, None
    ev = R / f"{name}.fault.log.events"
    if ev.exists() and t0:
        for line in ev.read_text().splitlines():
            p = line.split()
            if len(p) >= 3 and p[2] in ("kill", "die", "start", "pause", "unpause"):
                t = int(p[0]) / 1e9 - t0
                events.append({"t": t, "label": f"docker {p[2]}"})
                if p[2] in ("kill", "pause") and pg_down is None:
                    pg_down = t
                if p[2] == "unpause":
                    pg_ready = t
    fault_kind = "pause" if any(e["label"] == "docker pause" for e in events) else ("kill" if events else None)
    m = re.search(r"(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d\.\d+) UTC \[\d+\] LOG:  database system is ready",
                  (R / f"{name}.db.log").read_text() if (R / f"{name}.db.log").exists() else "")
    if m and t0:
        pg_ready = utc_epoch(m.group(1), "%Y-%m-%d %H:%M:%S.%f") - t0
        events.append({"t": pg_ready, "label": "PostgreSQL ready"})
    start_ev = next((e["t"] for e in events if e["label"] == "docker start"), None)
    ng = (R / f"{name}.nginx.log").read_text().splitlines() if (R / f"{name}.nginx.log").exists() else []
    nl = [utc_epoch(l[:19], "%Y/%m/%d %H:%M:%S") - t0 for l in ng if "no live upstreams" in l and t0]
    resets = [utc_epoch(l[:19], "%Y/%m/%d %H:%M:%S") - t0 for l in ng if "reset by peer" in l and t0]
    # nginx logs at 1 s resolution, so it is shown only as a window (never in the ms-ordered list).
    recovery = {}
    if pg_ready is not None:
        ok = [r for r in recs if r["status"] in (200, 409) and ans(r) >= pg_ready]
        for sname in sellers:
            ts = [ans(r) for r in ok if seller_of.get(r.get("upstream")) == sname]
            recovery[sname] = round(min(ts), 3) if ts else None
        if ok:
            events.append({"t": min(ans(r) for r in ok), "label": "first 200/409 answer after PostgreSQL ready"})
        # Sustained: the first second after which every later second (to the end of arrivals) has 200/409 answers.
        last = int(len(recs) / rate)
        good = [(per[s]["200"] + per[s]["409"]) > 0 for s in range(T + 1)]
        sus = next((s for s in range(int(pg_ready), last) if all(good[s:last])), None)
        if sus is not None:   # timestamped by the first answer inside that second (exact, not bucketed)
            t_sus = min(ans(r) for r in ok if int(ans(r)) == sus)
            events.append({"t": t_sus, "label": "sustained service resumed (every later second answered)"})
    events.sort(key=lambda e: e["t"])

    # Per-second component state for the status lanes.
    def pg_state(s):
        if pg_down is None or s + 1 <= pg_down or (pg_ready is not None and s >= pg_ready):
            return "up"
        if fault_kind == "pause":
            return "paused"
        return "recovering" if start_ev is not None and s >= start_ev else "down"

    lanes = {"PostgreSQL": [pg_state(s) for s in range(T + 1)],
             "nginx": ["no upstream" if nginx_own[s] else ("resets" if per[s]["502"] else "routing") for s in range(T + 1)]}
    for sname, series in sellers.items():
        lanes[sname] = ["errors" if series[s][500] else ("serving" if sum(series[s].values()) else "idle")
                        for s in range(T + 1)]

    results, _ = verify(d)
    rp = R / f"{name}.replay.txt"
    replay = [l for l in rp.read_text().splitlines() if l.strip()] if rp.exists() else []
    tot = Counter(cls(r["status"]) for r in recs)
    served = [r for r in recs if isinstance(r["status"], int)]
    return {
        "name": name, "label": label, "id": rid, "caption": caption, "T": T, "fault": fault_kind,
        "rate": rate, "requests": len(recs), "tickets": d["status"]["total_tickets"],
        "totals": {k: tot[k] for k in kinds if tot[k]},
        "served_per_s": round(len(served) / d["storm_seconds"], 1),
        "p50": round(pct([r["latency_ms"] for r in served], .5), 1),
        "p99": round(pct([r["latency_ms"] for r in served], .99), 1),
        "per_second": [{k: c[k] for k in kinds if c[k]} for c in per],
        "arrivals": arrivals,
        "lat_p50": [round(pct(v, .5), 1) if v else None for v in lat],
        "lat_p99": [round(pct(v, .99), 1) if v else None for v in lat],
        "sold": sold,
        "seller_answers": {s: [sum(c.values()) for c in series] for s, series in sellers.items()},
        "lanes": lanes, "events": [{"t": round(e["t"], 3), "label": e["label"]} for e in events],
        "pg_down": round(pg_down, 3) if pg_down is not None else None,
        "pg_ready": round(pg_ready, 3) if pg_ready is not None else None,
        "nginx_window": [round(min(nl), 1), round(max(nl) + 1, 1)] if nl else None,
        "nginx_resets": len(resets), "recovery": recovery,
        "checks": [{"name": k, "ok": ok, "detail": det} for k, (ok, det) in results.items()],
        "replay": replay,
    }


